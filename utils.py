def get_transmission_delay(uploader_edge_id, current_edge_server_id):
    edge_positions = {
        'Edge0': (0, 0),
        'Edge1': (0, 1),
        'Edge2': (1, 0),
        'Edge3': (1, 1),
    }

    pos1 = edge_positions.get(uploader_edge_id)
    pos2 = edge_positions.get(current_edge_server_id)

    if pos1 is None or pos2 is None:
        return -1  # 表示錯誤或無法計算
    return abs(pos1[0] - pos2[0]) + abs(pos1[1] - pos2[1])
